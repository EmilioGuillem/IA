create table if not exists public.guests (
  id bigint generated by default as identity primary key,
  group_id uuid not null,
  first_name text not null,
  last_name text not null,
  normalized_name text not null unique,
  attendance text not null check (attendance in ('going', 'not-going', 'unsure')),
  allergies text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists guests_attendance_idx on public.guests (attendance);
create index if not exists guests_allergies_idx on public.guests (allergies) where trim(allergies) <> '';

alter table public.guests enable row level security;

